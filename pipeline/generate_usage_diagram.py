LANE_COLORS = {"Read": "#DCEFE3", "AI": "#DDE7F7", "Collection": "#F6E7D8"}
LANE_EDGES = {"Read": "#3F8F5F", "AI": "#3B6BB5", "Collection": "#C57A2E"}


def _font() -> str:
    preferred = ["Apple SD Gothic Neo", "AppleGothic", "NanumGothic", "Noto Sans CJK KR", "DejaVu Sans"]
    available = {font.name for font in font_manager.fontManager.ttflist}
    return next(name for name in preferred if name in available)


def _box(ax, x, y, w, h, text, *, face, edge, size=11, weight="normal", radius=0.12):
    ax.add_patch(FancyBboxPatch((x, y), w, h, boxstyle=f"round,pad=0.02,rounding_size={radius}",
                                facecolor=face, edgecolor=edge, linewidth=1.6))
    ax.text(x + w / 2, y + h / 2, text, ha="center", va="center", fontsize=size, weight=weight, wrap=True)


def _arrow(ax, start, end, color="#555555"):
    ax.add_patch(FancyArrowPatch(start, end, arrowstyle="-|>", mutation_scale=16, linewidth=1.4, color=color))


def render(lang: str) -> Path:
    labels = LABELS[lang]
    plt.rcParams["font.family"] = _font()
    plt.rcParams["axes.unicode_minus"] = False
    fig, ax = plt.subplots(figsize=(16, 9), dpi=150)
    ax.set_xlim(0, 16)
    ax.set_ylim(0, 9)
    ax.axis("off")

    ax.text(8, 8.55, labels["title"], ha="center", va="center", fontsize=22, weight="bold")
    ax.text(8, 8.1, labels["subtitle"], ha="center", va="center", fontsize=12, color="#444444")

    # Entry points (left) feeding the shared runner.
    for index, text in enumerate(labels["entry"]):
        y = 6.55 - index * 1.15
        _box(ax, 0.35, y, 2.2, 0.85, text, face="#F2F2F2", edge="#777777", size=11)
        _arrow(ax, (2.55, y + 0.42), (3.05, 6.35))

    # Shared runner pipeline.
    _box(ax, 3.05, 5.55, 12.6, 1.6, "", face="#FAFAFA", edge="#999999", radius=0.2)
    ax.text(9.35, 6.95, labels["engine_title"], ha="center", va="center", fontsize=12.5, weight="bold", color="#333333")
    step_width, gap, x = 2.6, 0.5, 3.4
    for index, step in enumerate(labels["engine_steps"]):
        face = "#FFF4CC" if index == 2 else "#FFFFFF"
        _box(ax, x, 5.75, step_width, 0.95, step, face=face, edge="#888888", size=10.5)
        if index < len(labels["engine_steps"]) - 1:
            _arrow(ax, (x + step_width, 6.22), (x + step_width + gap, 6.22))
        x += step_width + gap

    # Column headings for lanes.
    column_x = [5.2, 9.4, 13.6]
    for cx, heading in zip(column_x, labels["columns"]):
        ax.text(cx, 5.2, heading, ha="center", va="center", fontsize=11, color="#666666", weight="bold")

    # Three lanes.
    lane_height, lane_gap, top = 1.15, 0.22, 5.0
    for index, (key, name, requirement, cells) in enumerate(labels["lanes"]):
        y = top - lane_height - index * (lane_height + lane_gap)
        _box(ax, 0.35, y, 15.3, lane_height, "", face=LANE_COLORS[key], edge=LANE_EDGES[key], radius=0.18)
        ax.text(0.55, y + lane_height - 0.32, key, ha="left", va="center", fontsize=13, weight="bold", color=LANE_EDGES[key])
        ax.text(0.55, y + lane_height / 2, name, ha="left", va="center", fontsize=10.5, color="#333333")
        ax.text(0.55, y + 0.26, requirement, ha="left", va="center", fontsize=9.5, color="#555555")
        cell_width = 3.4
        for cx, text in zip(column_x, cells):
            _box(ax, cx - cell_width / 2, y + 0.2, cell_width, lane_height - 0.4, text, face="#FFFFFF", edge=LANE_EDGES[key], size=9.5)
        for left, right in zip(column_x, column_x[1:]):
            _arrow(ax, (left + cell_width / 2, y + lane_height / 2), (right - cell_width / 2, y + lane_height / 2), color=LANE_EDGES[key])

    for index, line in enumerate(labels["footer"]):
        ax.text(8, 0.62 - index * 0.32, line, ha="center", va="center", fontsize=10.5, color="#333333")

    output = OUTPUTS[lang]
    fig.savefig(output, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    return output


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lang", choices=sorted(OUTPUTS), action="append")
    args = parser.parse_args(argv)
    for lang in args.lang or sorted(OUTPUTS):
        print(render(lang))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
