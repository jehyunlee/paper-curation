#!/usr/bin/env python3
"""Render the three-path usage diagram (Read / AI / Collection) deterministically.

Unlike the PaperBanana workflow illustration, this figure needs no API key:
it is drawn with matplotlib from the labels below so it stays in sync with the
documented user flow and can be regenerated by anyone.

Usage:
  PYTHONUTF8=1 python pipeline/generate_usage_diagram.py            # both languages
  PYTHONUTF8=1 python pipeline/generate_usage_diagram.py --lang ko  # one language
"""
